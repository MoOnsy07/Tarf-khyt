/* ============================================================
   خطوبة مؤجلة — إصلاح كشف الجاني بعد المداهمة
   المداهمة تنقذ معتز وتثبت مكان الاحتجاز، لكنها لا تكشف هوية
   المسؤول وحدها قبل ما اللاعب يعمل الاتهام النهائي.
   ============================================================ */
(() => {
  'use strict';
  if (typeof CASE_POSTPONED_ENGAGEMENT === 'undefined') return;

  const c = CASE_POSTPONED_ENGAGEMENT;
  const evidence = id => (c.evidence || []).find(e => e && e.id === id);
  const action = id => (c.investigationActions || []).find(a => a && a.id === id);

  const rescued = evidence('moutaz_rescued_verified_v2');
  if (rescued) {
    rescued.title = 'العثور على معتز حيًا في المخزن';
    rescued.short = 'المداهمة عثرت على معتز داخل غرفة جانبية مقفولة من الخارج';
    rescued.full = 'بعد اكتمال قرائن السيارة والملكية وإشارة الهاتف، تمت مداهمة المخزن وعُثر على معتز حيًا داخل غرفة جانبية مقفولة من الخارج، بينما كان هاتفه في مكان منفصل. معتز كان مرتبكًا بعد الاحتجاز وقال إنه خرج لمقابلة شخص بخصوص موضوع مالي ثم لم يستطع المغادرة، لكن حالته وقت الإنقاذ لم تسمح له بتأكيد مين بالضبط أغلق عليه. نتيجة المداهمة تثبت مكان الاحتجاز وتوقيت وجوده هناك، لكنها لا تحسم هوية المسؤول وحدها.';
  }

  const raid = action('engagement_raid_verified_warehouse_v2');
  if (raid) {
    raid.successText = 'تم العثور على معتز حيًا داخل غرفة جانبية مقفولة من الخارج. المداهمة أثبتت مكان الاحتجاز، لكنها لا تحسم هوية المسؤول وحدها.';
  }

  const hassan = (c.suspects || []).find(s => s && s.id === 'debt_collector_hassan_p');
  if (hassan) {
    const q = (hassan.questions || []).find(x => x && x.closesInterrogation);
    if (q) {
      q.q = 'الكاميرا أثبتت إن معتز ركب عربيتك، وبعدها اتلاقى في مخزن مرتبط بيك. تفسر التسلسل ده إزاي؟';
      q.requires = ['hassan_p_vehicle_camera','moutaz_rescued_verified_v2'];
      q.a = '(بيتوتر) "قابلته فعلًا عشان نتكلم في الدين، وركب معايا. وصلنا ناحية المنطقة الصناعية واتخانقنا، وبعدها سبت المكان. معرفش إزاي اتلاقى جوه المخزن، ومش هاعترف بحاجة لمجرد إن المكان كان مرتبط بعقد قديم."';
    }
  }

  c.rescueRevealFixVersion = '2026-08-24-v1';
})();
